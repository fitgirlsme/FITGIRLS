/**
 * 영업리스트 업체를 제휴 피트니스로 즉시 등록 및 핏걸즈 웹사이트 동기화
 */
export const convertLeadToPartnerFitness = async (lead, options = {}) => {
  try {
    if (!lead || !lead.name) throw new Error('유효한 업체 정보가 필요합니다.');

    const partnerPayload = {
      gym_name: lead.name,
      location: lead.roadAddress || lead.address || (lead.region ? `${lead.region.sido || ''} ${lead.region.sigungu || ''}`.trim() : '위치 정보 없음'),
      phone: lead.phone || '',
      category: lead.category || (lead.name.includes('필라테스') ? 'pilates' : 'fitness'),
      contact_person: options.contact_person || '',
      instagram: options.instagram || '',
      partnership_type: options.partnership_type || '바디프로필 제휴',
      benefit: options.benefit || '회원 11만원 할인 + 예약 건당 피트니스 33,000 FIT 포인트 지급',
      status: options.status || '제휴중',
      start_date: options.start_date || new Date().toISOString().slice(0, 10),
      memo: lead.memo ? `[영업리스트 연동] ${lead.memo}` : '[영업리스트 발굴 센터]',
      lead_id: lead.id || '',
      source: 'sales_lead',
      show_on_fitgirls: true,
      createdAt: serverTimestamp(),
      updatedAt: serverTimestamp()
    };

    const partnerDocRef = await addDoc(collection(db, 'partner_fitness'), partnerPayload);
    const newPartnerId = partnerDocRef.id;

    try {
      await syncFitnessToFitgirls({
        id: newPartnerId,
        ...partnerPayload
      });
    } catch (syncErr) {
      console.warn('Fitgirls Web Sync Error:', syncErr);
    }

    if (lead.id) {
      try {
        const leadDocRef = doc(db, 'sales_leads', lead.id);
        await updateDoc(leadDocRef, {
          status: 'partnered',
          partnerFitnessId: newPartnerId,
          partneredAt: serverTimestamp(),
          updatedAt: serverTimestamp()
        });
      } catch (leadUpdateErr) {
        console.warn('Lead Update Error:', leadUpdateErr);
      }
    }

    return {
      partnerId: newPartnerId,
      ...partnerPayload
    };
  } catch (error) {
    console.error('Convert Lead To Partner Error:', error);
    throw error;
  }
};

