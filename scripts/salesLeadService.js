/**
 * 카카오 로컬 검색 API를 통해 실시간 피트니스/필라테스 업체 검색
 */
export const searchPortalFitnessLeads = async (queryText, page = 1) => {
  try {
    const apiKey = getKakaoApiKey();
    const url = `https://dapi.kakao.com/v2/local/search/keyword.json?query=${encodeURIComponent(queryText)}&page=${page}&size=15`;
    
    const response = await fetch(url, {
      headers: {
        Authorization: `KakaoAK ${apiKey}`
      }
    });

    if (!response.ok) {
      throw new Error(`카카오 API 호출 실패: ${response.status}`);
    }

    const data = await response.json();
    const items = (data.documents || []).map(doc => {
      const isPilates = doc.place_name.includes('필라테스') || (doc.category_name || '').includes('필라테스');
      return {
        sourceId: doc.id,
        name: doc.place_name,
        category: isPilates ? 'pilates' : 'fitness',
        categoryName: isPilates ? '필라테스' : '피트니스',
        rawCategory: doc.category_name || '',
        phone: doc.phone || '',
        roadAddress: doc.road_address_name || '',
        address: doc.address_name || '',
        placeUrl: doc.place_url || '',
        x: doc.x || null,
        y: doc.y || null,
        lat: doc.y ? parseFloat(doc.y) : null,
        lng: doc.x ? parseFloat(doc.x) : null
      };
    });

    return {
      items,
      totalCount: data.meta?.total_count || 0,
      isEnd: data.meta?.is_end ?? true
    };
  } catch (error) {
    console.error('Search Portal Fitness Leads Error:', error);
    throw error;
  }
};

/**
 * Firestore DB에서 영업 리스트 가져오기
 */
export const fetchSalesLeads = async (filterRegion = null, filterCategory = null, searchKeyword = '') => {
  try {
    const leadsRef = collection(db, 'sales_leads');
    const q = query(leadsRef, orderBy('createdAt', 'desc'));
    const snapshot = await getDocs(q);

    let list = snapshot.docs.map(docSnap => ({
      id: docSnap.id,
      ...docSnap.data()
    }));

    if (filterRegion?.sido) {
      list = list.filter(item => item.region?.sido === filterRegion.sido);
    }
    if (filterRegion?.sigungu) {
      list = list.filter(item => item.region?.sigungu === filterRegion.sigungu);
    }
    if (filterRegion?.dong) {
      list = list.filter(item => item.region?.dong === filterRegion.dong);
    }
    if (filterCategory && filterCategory !== 'all') {
      list = list.filter(item => item.category === filterCategory);
    }
    if (searchKeyword && searchKeyword.trim()) {
      const kw = searchKeyword.toLowerCase();
      list = list.filter(item =>
        (item.name && item.name.toLowerCase().includes(kw)) ||
        (item.roadAddress && item.roadAddress.toLowerCase().includes(kw)) ||
        (item.phone && item.phone.includes(kw)) ||
        (item.memo && item.memo.toLowerCase().includes(kw))
      );
    }

    return list;
  } catch (error) {
    console.error('Fetch Sales Leads Error:', error);
    throw error;
  }
};

